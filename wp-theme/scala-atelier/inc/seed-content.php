function scala_prose_catalog(): string {
	return <<<'HTML'
<p>Каталог зручно гортати, коли вже знаєш, що шукаєш. Якщо ще ні — почніть не з тканини й не з фотографій, а з двох простих питань про кімнату.</p>

<h3>Скільки світла ви хочете зберегти</h3>
<p>Це головне рішення, і воно визначає все інше. Якщо кімнаті бракує сонця, потрібен один шар легкого полотна: тюль із льону-сітки, вуаль або батист розсіюють промінь і не крадуть яскравість. Якщо світла забагато або вікно виходить на сонячний бік, додають другий шар — портьєри, які закривають вікно ввечері. Коли ж потрібна справжня темрява, як у спальні чи дитячій, працює лише щільна тканина з блекаут-підкладкою.</p>
<p>Проміжний варіант — димаут: він приглушує світло, але не занурює кімнату в цілковиту темряву. Це компроміс для тих, хто не любить прокидатися в чорній кімнаті.</p>

<h3>Скільки місця готові віддати</h3>
<p>Портьєри й тюль потребують простору обабіч вікна: полотно у зібраному стані має куди зсуватися, інакше воно постійно затуляє частину скла. Якщо стіни біля вікна зайняті меблями або отвір нестандартний, доречніші компактні конструкції.</p>
<ul>
<li><strong>Римські штори</strong> збираються рівними горизонтальними складками вгору й не виходять за межі отвору — вибір для кухні, кабінету й еркера.</li>
<li><strong>Рулонні системи</strong> ховаються в касету просто на стулці вікна: підвіконня лишається вільним, а мити скло можна не знімаючи полотна.</li>
<li><strong>Дерев'яні жалюзі</strong> дають найточніший контроль світла — кут ламелі повертається так, щоб прибрати відблиск, але лишити видимість.</li>
<li><strong>Японські панелі</strong> рухаються рівними полотнами по треку. Їх беруть для панорамного скління й для зонування простору.</li>
<li><strong>Австрійські штори</strong> — м'які фестони, класичне рішення для вітальні та спальні, коли інтер'єр витримано в декоративному ключі.</li>
</ul>

<h3>Тканина: на що дивитися, крім кольору</h3>
<p>Колір ви оберете за хвилину, а жити з тканиною доведеться роками, тому важливіші три інші речі. <strong>Щільність</strong> визначає, скільки світла проходить крізь полотно й наскільки кімната закрита від сусідніх вікон. <strong>Склад</strong> відповідає за поведінку: натуральний льон гарно драпірується, але дає усадку й мнеться; синтетика тримає форму й менше вигорає; змішані тканини поєднують і те, і те. <strong>Вага</strong> визначає, як ляже складка: легке полотно дає дрібну хвилю, важке — велику спокійну драпіровку.</p>
<p>На сонячному боці окремо варто питати про стійкість до вигоряння: тканини без відповідного оздоблення втрачають колір нерівномірно, і за пару сезонів це стає помітно на згинах.</p>

<h3>Карниз — частина рішення, а не дрібниця</h3>
<p>Висота, на якій закріплено карниз, змінює пропорції кімнати сильніше за будь-який декор. Винесений під саму стелю, він візуально витягує стіну; закріплений одразу над отвором — навпаки, приземлює її. Для спальні карниз ще й виносять ширше за отвір, щоб ранкове світло не пробивалося збоку від полотна. Прихований трек у стельовій ніші дає найчистіший вигляд, але нішу потрібно закладати ще на етапі ремонту — про це варто подумати заздалегідь.</p>

<h3>Комплектація: карнизи, треки й механізми</h3>
<p><strong>Профільний карниз</strong> — універсальне рішення: витримує вагу портьєр, дозволяє два ряди й ховається за декоративною планкою. <strong>Стельовий трек</strong> монтується впритул до стелі й майже не видимий — саме він дає ефект полотна, що спадає просто зі стелі. <strong>Прихована ніша</strong> — найчистіший варіант, але її закладають ще на етапі ремонту.</p>
<p><strong>Електрокарниз</strong> має сенс там, де до вікна складно дотягнутися: панорамне скління, високі отвори, зимовий сад. Керується з пульта або застосунку, вимагає підведеного живлення. Окремо йде <strong>блекаут-підкладка</strong> — не тип штор, а другий шар, який підшивається до портьєри зсередини: додає ваги, покращує драпіровку й дає темряву, якої сама тканина не забезпечить.</p>

<h3>Що є в наявності, а що шиється під замовлення</h3>
<p>Усі вироби в цьому каталозі шиються під конкретне вікно: готових розмірів ми не тримаємо. Тканини з представлених колекцій дизайнер привозить у вигляді відрізів на замір; якщо потрібного артикула немає в наявності, його замовляють у постачальника — строк менеджер називає після того, як конструкцію й тканину узгоджено.</p>
<p>Остаточний вибір усе одно робиться на замірі. Дизайнер привозить відрізи з відповідних колекцій просто до вас у Київ, і при вашому освітленні половина варіантів відпадає сама — а той, що лишається, зазвичай виявляється не тим, який ви обрали за фотографією.</p>
HTML;
}

