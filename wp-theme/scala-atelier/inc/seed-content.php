<h3>Замір — це не просто розміри вікна</h3>
<p>Рулетка тут найпростіша частина. Дизайнер дивиться, куди виходить вікно й коли в кімнату потрапляє пряме сонце, перевіряє рівність стелі та стін, шукає, де можна закріпити карниз і чи витримає це кріплення вагу тканини. Виміряти треба не лише отвір, а й відстань до стелі, глибину ніші, виступ підвіконня й радіатора: від них залежить, якої довжини буде полотно й де воно почне збиратися.</p>
<p>Тоді ж на місці приміряються відрізи. Це і є сенс виїзду: тканину видно у вашому освітленні, поруч із вашими стінами й меблями, а не на екрані.</p>

<h3>Пошиття: складку рахують до розкрою</h3>
<p>Кількість тканини визначає не ширина вікна, а коефіцієнт складки — у скільки разів полотно ширше за карниз. Від нього залежить, чи буде драпіровка щільною й глибокою, чи полотно висітиме майже рівним. Легкий тюль потребує більшого коефіцієнта, важкий оксамит — меншого, інакше складка стане громіздкою. Помилка на цьому етапі не виправляється потім нічим, тому розрахунок роблять до розкрою, а не після.</p>
<p>Далі — обробка низу з обважнювачем, щоб полотно висіло рівно, і кріплення під обраний спосіб: стрічка, люверси або бігунки для прихованого трека.</p>

<h3>Монтаж — момент, коли видно якість роботи</h3>
<p>Карниз встановлюють по рівню, а не «на око»: перекіс у кілька міліметрів на довгій стіні читається одразу. Після того як полотна повішені, складку формують руками й фіксують — саме тому нові штори перший тиждень краще не чіпати. Готове вікно здають вам на місці: перевіряєте, як полотно ходить, чи змикається щільно, чи немає зазору збоку.</p>

<h3>З якими тканинами працюємо</h3>
<p>Асортимент ділиться на три групи за поведінкою полотна. <strong>Прозорі та напівпрозорі</strong> — льон-сітка, вуаль, батист, деворе: вони працюють зі світлом, а не з темрявою, і потребують більшого коефіцієнта складки, щоб не виглядати пласко. <strong>Щільні портьєрні</strong> — оксамит, жакард, блекаут: тримають форму, дають глибоку драпіровку, закривають вікно ввечері. <strong>Технічні</strong> — полотна для рулонних систем і римських штор, які мають лежати рівно й не мнутися.</p>
<p>Для кожної групи важливі різні речі. У прозорих ми дивимось на рівність нитки й на те, як тканина поводиться під прямим сонцем. У щільних — на вагу й стійкість фарбування: саме вони визначають, чи не вигорить полотно нерівномірно за пару сезонів на південному боці. У технічних — на антистатичне й пилевідштовхувальне оздоблення.</p>

<h3>Для дизайнерів та студій</h3>
<p>Ми регулярно працюємо в чужих проєктах — коли концепція вже затверджена, а текстиль потрібно втілити в матеріалі й строках. Беремо на себе підбір тканин під палітру проєкту, розрахунки, пошиття й монтаж, лишаючи авторство рішення за дизайнером. Умови співпраці для студій обговорюються окремо: напишіть у Telegram або WhatsApp.</p>

<h3>Де ми працюємо</h3>
<p>Основна географія — Київ: дизайнер приїздить зі зразками в межах міста безкоштовно. Беремо і квартири, і приватні будинки, і комерційні простори — салони, офіси, заклади, де текстиль має витримувати щоденне навантаження. Якщо об'єкт за межами Києва, умови виїзду узгоджуємо окремо.</p>

<h3>Що ми не робимо</h3>
<p>Ми не називаємо ціну до заміру й не продаємо готові розміри «на вибір». Штора, підігнана під конкретне вікно, коштує дорожче за фабричну, і сенс у ній лише тоді, коли вона справді зроблена під ваш отвір, ваше світло й ваш спосіб користуватися кімнатою. Якщо завдання простіше — чесніше сказати про це одразу.</p>
