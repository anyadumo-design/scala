/**
 * Вписує описи в проєкти.
 *
 * @return int Скільки проєктів оновлено.
 */
function scala_fill_project_copy(): int {
	if ( ! function_exists( 'scala_expand_guide_links' ) || ! function_exists( 'scala_write_guide' ) ) {
		return 0;
	}

	$changed = 0;

	foreach ( scala_project_copy() as $slug => $html ) {
		$found = get_posts(
			array(
				'name'           => $slug,
				'post_type'      => 'scala_project',
				'post_status'    => array( 'publish', 'draft', 'private' ),
				'posts_per_page' => 1,
				'fields'         => 'ids',
			)
		);

		if ( ! $found ) {
			continue;
		}

		$id      = (int) $found[0];
		$now     = (string) get_post_field( 'post_content', $id );
		$ours    = (string) get_post_meta( $id, '_scala_project_copy', true );
		$empty   = '' === trim( wp_strip_all_tags( $now ) );
		$content = scala_expand_guide_links( $html );

		// Текст людини — недоторканний.
		if ( ! $empty && md5( $now ) !== $ours ) {
			continue;
		}

		if ( $now === $content ) {
			continue;
		}

		scala_write_guide(
			array(
				'ID'           => $id,
				'post_content' => $content,
			)
		);

		update_post_meta( $id, '_scala_project_copy', md5( (string) get_post_field( 'post_content', $id ) ) );
		++$changed;
	}

	return $changed;
}
