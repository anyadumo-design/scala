/**
 * Точкові правки тексту в матеріалах, які живуть тільки в базі.
 *
 * Сторінки видів штор і текст каталогу тема записала один раз, під час
 * першого наповнення, і далі їх не звіряє із заготовкою: це вже вміст
 * сайту, який могли редагувати руками. Тому переписати їх цілком не
 * можна. Але окреме невдале речення виправити можна: шукаємо рівно
 * старий варіант і ставимо новий.
 *
 * Якщо речення вже змінили руками, старого варіанта в тексті немає — і
 * правка просто нічого не робить. Повторний запуск теж нічого не
 * робить: після заміни старого речення вже немає.
 *
 * @package scala
 */

defined( 'ABSPATH' ) || exit;

/**
 * Пари «старе речення → нове».
 *
 * @return array<string, string>
 */
function scala_copy_fixes(): array {
	/*
	 * «Готових розмірів у нас немає» стояло майже на кожній сторінці,
	 * здебільшого останнім реченням. Власниця: «звучить тупо». Це
	 * заперечення очевидного — ательє штор і так шиє на замовлення, — а
	 * повторене двадцять разів воно ставало мовним тиком.
	 */
	return array(
		'Готових розмірів у нас немає взагалі, тому нестандарт — звичайна робота, а не виняток.'
			=> 'Нестандарт для нас — звичайна робота, а не виняток.',
		'Готових розмірів не буває: ширина й довжина рахуються під ваше вікно та карниз.'
			=> 'Ширина й довжина залежать і від вікна, і від карниза.',
		'Ми шиємо римські штори в Києві під конкретне вікно за власними замірами: готових розмірів тут не буває, бо кожен сантиметр змінює те, як ляжуть складки.'
			=> 'Ми шиємо римські штори в Києві за власними замірами, бо навіть сантиметр похибки видно по складках.',
		'після заміру на місці. Готових розмірів немає — система рахується під ваше вікно.'
			=> 'після заміру на місці.',
		'Далі жалюзі виготовляють під ваше вікно — готових розмірів немає.'
			=> 'Далі за цими замірами виготовляють жалюзі.',
		'Кожна штора шиється під конкретне вікно — готових розмірів у нас немає.'
			=> 'Штору кроять тільки після цього.',
		'Усі вироби в цьому каталозі шиються під конкретне вікно: готових розмірів ми не тримаємо.'
			=> 'Усі вироби в цьому каталозі шиються на замовлення.',
	);
}

/**
 * Замінює старі речення в рядку або в масиві рядків.
 *
 * @param mixed $value Рядок, масив рядків або рядків-масивів (FAQ).
 * @param array $fixes Пари заміни.
 * @return mixed
 */
function scala_copy_fix_value( $value, array $fixes ) {
	if ( is_string( $value ) ) {
		return strtr( $value, $fixes );
	}

	if ( is_array( $value ) ) {
		foreach ( $value as $key => $item ) {
			$value[ $key ] = scala_copy_fix_value( $item, $fixes );
		}
	}

	return $value;
}

/**
 * Проходить сторінки видів штор і каталог.
 *
 * @return int Скільки записів змінено.
 */
function scala_apply_copy_fixes(): int {
	$fixes = scala_copy_fixes();

	if ( ! $fixes ) {
		return 0;
	}

	$ids = get_posts(
		array(
			'post_type'      => array( 'scala_type', 'page' ),
			'post_status'    => array( 'publish', 'draft', 'private' ),
			'posts_per_page' => -1,
			'fields'         => 'ids',
		)
	);

	$changed = 0;

	foreach ( $ids as $id ) {
		$id      = (int) $id;
		$touched = false;

		$content = (string) get_post_field( 'post_content', $id );
		$fixed   = scala_copy_fix_value( $content, $fixes );

		if ( $fixed !== $content ) {
			/*
			 * Ревізія зі старим текстом — щоб правку можна було
			 * відкотити з редактора. Санітайзер не потрібен: міняємо
			 * лише речення, розмітка лишається та сама.
			 */
			wp_save_post_revision( $id );

			if ( function_exists( 'scala_write_guide' ) ) {
				scala_write_guide( array( 'ID' => $id, 'post_content' => $fixed ) );
			} else {
				wp_update_post( array( 'ID' => $id, 'post_content' => $fixed ) );
			}

			$touched = true;
		}

		// Вступ, короткий опис і відповіді FAQ сторінки виду штор.
		foreach ( array( 'lead', 'short', 'faq' ) as $key ) {
			$meta  = get_post_meta( $id, '_scala_' . $key, true );
			$fixed = scala_copy_fix_value( $meta, $fixes );

			if ( $fixed !== $meta ) {
				update_post_meta( $id, '_scala_' . $key, $fixed );
				$touched = true;
			}
		}

		if ( $touched ) {
			++$changed;
		}
	}

	return $changed;
}
